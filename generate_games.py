def strip_backdrop(inner):
    """Drop a scene's own background so it can sit inside a card."""
    return inner.split('stroke-width="2"/>', 1)[1]


def readme_block():
    arm_btn = "".join(f'<a href="arm/{o}.md"><img src="arm/btn/pick-{o}.svg" width="16%" alt="Pick {OBJ[o][0].lower()}"></a>\n' for o in "rby")
    bat_btn = "".join(f'<a href="battle/s{st}/start.md"><img src="battle/btn/stage{st}.svg" width="16%" alt="Fight the {STAGES[st]["name"].title()}"></a>\n' for st in STAGES)
    return ('<!-- play:start (generated by generate_games.py) -->\n<p align="center">\n'
            '<a href="arm/README.md"><img src="arm/card.svg" width="49%" alt="Teach the arm: a click game. Show a robot arm a pick and place task and it repeats the order by itself."></a>\n'
            '<a href="battle/README.md"><img src="battle/card.svg" width="49%" alt="Robot battle: a click game. A turn-based duel against three enemy bots."></a>\n'
            '<br>\n' + arm_btn + bat_btn +
            '</p>\n<p align="center"><sub>Two games that run right here in the README: every click opens the next pre-rendered state. '
            f'Want the real thing? <a href="{PAGES_URL}"><b>Play the live 3D version</b></a>: drag a 6-axis arm, teach it a task, then watch it repeat the task by itself.</sub></p>\n'
            '<!-- play:end -->')


def update_readme():
    p = ROOT / "README.md"
    text = p.read_text(encoding="utf-8")
    block = readme_block()
    if "<!-- play:start" in text:
        text = re.sub(r"<!-- play:start.*?<!-- play:end -->", lambda _: block, text, flags=re.S)
    else:
        text = text.replace("<details>", block + "\n\n<details>", 1)
    write(p, text)


