def enemy_action(stage, rnd, ehp):
    s = STAGES[stage]
    pat = s["rage"] if s["rage"] and ehp <= 2 else s["pattern"]
    return pat[(rnd - 1) % len(pat)]


def resolve(pa, ea):
    """One exchange. Returns (damage to enemy, damage to player, energy change, note)."""
    de = {"A": 1, "O": 3}.get(pa, 0)
    if de and ea == "G":
        de = max(0, de - 2)
    if de and ea == "R":
        de += 1
    dp = {"J": 1, "H": 2, "K": 3}.get(ea, 0)
    if pa == "S":
        dp = max(0, dp - 2)
    if pa == "O" and ea == "K":
        dp = 0
    return de, dp, {"C": 1, "O": -2}.get(pa, 0)


def step(stage, st, pa):
    """st = (round, player hp, enemy hp, energy). Returns ('win'|'flawless'|'lose'|'timeout', None) or ('go', state, enemy action)."""
    rnd, php, ehp, en = st
    ea = enemy_action(stage, rnd, ehp)
    de, dp, den = resolve(pa, ea)
    ehp2 = max(0, ehp - de)
    if ehp2 == 0:                                   # I act first: a destroyed enemy does not hit back
        return ("flawless" if php == PHP else "win"), None, ea
    php2 = max(0, php - dp)
    if php2 == 0:
        return "lose", None, ea
    if rnd == ROUNDS:
        return "timeout", None, ea
    return "go", (rnd + 1, php2, ehp2, min(EMAX, en + den)), ea


def actions(en):
    return ["A", "S", "C"] + (["O"] if en >= 2 else [])


def battle_graph(stage):
    """All reachable pages of a stage: {(state, last player action, last enemy action)}."""
    first = ((1, PHP, STAGES[stage]["hp"], 0), "", "")
    seen, todo = {first}, [first]
    while todo:
        st, _, _ = todo.pop()
        for pa in actions(st[3]):
            kind, nxt, ea = step(stage, st, pa)
            if kind == "go" and (nxt, pa, ea) not in seen:
                seen.add((nxt, pa, ea)); todo.append((nxt, pa, ea))
    return seen


