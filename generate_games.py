"""Builds the two click games that run inside the GitHub README: Teach the arm and Robot battle.

A README cannot run code, so there is no server and no Actions here. Every game state is its
own tiny markdown page with an animated SVG, and every button is a plain relative link to the
page of the next state. This script pre-renders the whole state graph:

  arm/      Teach the arm: pick an object, pick a bin, three times. The robot then repeats the
            taught order, also from shuffled start positions.     (about 280 pages)
  battle/   Robot battle: a turn-based duel over three stages.      (pages share ~200 images)

It also rewrites the block between <!-- play:start --> and <!-- play:end --> in README.md.
Everything is deterministic: same script, same bytes. Never hand-edit the generated files.

Run:   python generate_games.py           (needs fonttools + brotli, like generate_assets.py)
Test:  python tests/test_graph.py
"""

